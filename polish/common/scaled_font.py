"""Python-side 8x8 bitmap font renderer at 4x/8x scale for title cards.

Mirrors the substrate's 8x8 bitmap aesthetic (boot/data.asm + boot/auryn.asm) but at
scale-up multiples for boot animation title cards and About demo headers. Chunky
pixel-art on purpose — coherent with 64KB-class bare-metal substrate aesthetic.

The font_glyphs dict is a Python mirror of a subset of the substrate's font data.
We bundle only the characters needed for title cards (uppercase letters, digits,
period, colon, space). Full 256-character font would be ~2KB; we ship the subset.

D4.1 (polish-vs-credential): substrate font lives in boot/data.asm and is the
production renderer; this Python mirror is showroom-only.
"""

