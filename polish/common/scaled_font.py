GLYPH_PIX = 8  # base glyph dimension


def glyph_pixels(ch: str) -> Sequence[Sequence[int]]:
    """Return 8x8 pixel matrix for character. Unknown chars map to space.

    Returns a list of 8 rows; each row is a list of 8 ints (0 or 1).
    """
    rows = FONT_8X8.get(ch.upper(), FONT_8X8[' '])
    out = []
    for row in rows:
        bits = [(row >> (7 - i)) & 1 for i in range(8)]
        out.append(bits)
    return out


def render_glyph_scaled(ch: str, scale: int,
                        color_fn=None,
                        bg_color: Tuple[int, int, int] = (0, 0, 0)):
    """Render a glyph at scale-up; return list of (x, y, rgb) pixels.

    Each 8x8 pixel becomes a scale×scale block. color_fn(y_norm) → RGB if set;
    else uniform white. y_norm in [0, 1] across the glyph's vertical extent.

    Returns: list of (px, py, (r, g, b)) tuples for foreground pixels only.
    """
    if color_fn is None:
        color_fn = lambda y_norm: (240, 240, 240)
    pixels = []
    rows = glyph_pixels(ch)
    total_height = GLYPH_PIX * scale
    for gy in range(GLYPH_PIX):
        for gx in range(GLYPH_PIX):
            if rows[gy][gx]:
                for dy in range(scale):
                    for dx in range(scale):
                        px = gx * scale + dx
                        py = gy * scale + dy
                        y_norm = py / max(total_height - 1, 1)
                        pixels.append((px, py, color_fn(y_norm)))
    return pixels


def text_width(text: str, scale: int, spacing: int = 1) -> int:
    """Width of rendered text in pixels (per-glyph scale + inter-glyph spacing)."""
    if not text:
        return 0
    return len(text) * (GLYPH_PIX * scale) + (len(text) - 1) * spacing


def render_text_scaled(text: str, scale: int,
                       color_fn=None,
                       spacing: int = 1):
    """Render a text string at scale; return list of (x, y, rgb) pixels.

    Each glyph is positioned at x = i * (GLYPH_PIX * scale + spacing).
    """
    pixels = []
    for i, ch in enumerate(text):
        glyph_pixels_list = render_glyph_scaled(ch, scale, color_fn)
        x_off = i * (GLYPH_PIX * scale + spacing)
        for px, py, rgb in glyph_pixels_list:
            pixels.append((px + x_off, py, rgb))
    return pixels
